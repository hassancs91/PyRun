"""
Docs for each integration, generated from its code (2.5 Stage 6, T26).

``docs/integrations/<key>.md`` is written from the integration's ``api.py``
(title, summary, example) and its script-facing module (the module docstring,
each declared function's signature and docstring), plus the shared error codes.
The files are committed, so they ship in the image and ``help.search`` indexes
them; ``manage.py integration_docs`` rewrites them and ``--check`` fails when
one is out of date (a test does the same).
"""

import inspect
import re
from pathlib import Path

from django.conf import settings

from core.integrations import framework
from core.integrations.presets import SMTP

AUTH_LABELS = {
    "oauth2": "OAuth (Connect or a pasted token)",
    "api_key": "an API key",
    "bearer": "a bearer token",
    "basic": "a username and password",
    "smtp": "an SMTP login",
}


def path_for(integration, root=None) -> Path:
    return Path(root or settings.BASE_DIR) / "docs" / "integrations" / f"{integration.key}.md"


def _doc(obj) -> str:
    """``obj``'s docstring as Markdown: indented example lines fenced, ``code`` as `code`.

    Examples are told apart by their indentation relative to the text below
    the summary line, so a docstring with an example has a text line before it
    ("For example:"): Python 3.13 strips a docstring's common indentation
    itself, as ``inspect.cleandoc`` does, and an example-only body would lose it.
    """
    out, block = [], []
    for line in [*inspect.cleandoc(obj.__doc__ or "").split("\n"), ""]:
        if line.startswith("    ") and (block or not out or out[-1] == ""):
            block.append(line[4:])
            continue
        if block:
            out += ["```python", *block, "```"]
            block = []
        out.append(re.sub(r"``([^`]+)``", r"`\1`", line.rstrip()))
    return "\n".join(out).strip()


def _or(words) -> str:
    return words[0] if len(words) == 1 else f"{', '.join(words[:-1])} or {words[-1]}"


def render(integration) -> str:
    """The Markdown page of ``integration``."""
    _pc, client = framework.script_helpers()
    waits = [min(client.MAX_BACKOFF, client.BACKOFF * 2 ** i) for i in range(client.MAX_RETRIES)]
    module = framework.script_module(integration)
    # A module whose service pauses for a fixed time after a 429 declares it (and passes it to its client).
    pause = getattr(module, "RATE_LIMIT_WAIT", None)
    otherwise = (f"{pause:g} seconds after a 429 that doesn't say (the service's documented pause), "
                 f"{_or([f'{w:g}' for w in waits])} seconds after a 5xx" if pause is not None
                 else f"{_or([f'{w:g}' for w in waits])} seconds")
    preset = framework.load_preset(integration.provider)
    kinds = [AUTH_LABELS.get(k, k) for k in preset.auth_kinds]
    lines = [
        f"<!-- Generated by `manage.py integration_docs` from core/integrations/{integration.key}/api.py and "
        f"{integration.module_name}: edit those, then run it again. -->",
        "",
        f"# {integration.title} integration (`{integration.module_name}`)",
        "",
        _doc(module),
        "",
        "## Connection",
        "",
        f"It uses a connection of the **{preset.label}** kind (provider `{preset.key}`), which signs in with "
        f"{_or(kinds)}. Add one under "
        "**Connections** in the sidebar and grant it to the script. Every function takes `connection=`: the "
        f"connection's name, or nothing for the script's one `{preset.key}` connection.",
        "",
    ]
    if preset.is_http and SMTP not in preset.auth_kinds:
        # A module on another API host of the service (BASE_URL, its client's base_url) sends them there.
        host = getattr(module, "BASE_URL", None)
        where = f"`{host}`" if host else "the connection's base URL"
        lines += [
            f"The credentials go only to {where}; a redirect elsewhere goes on without them.",
            "",
        ]
    if integration.example:
        lines += ["## Example", "", "```python", integration.example.rstrip(), "```", ""]
    lines += ["## Functions", ""]
    for name, fn in framework.public_functions(integration):
        lines += [f"### {name}", "", "```python", f"{integration.key}.{framework.signature(fn)}", "```", "",
                  _doc(fn), ""]
    # A module that isn't HTTP (smtp) declares its own codes and the paragraph about them.
    codes = getattr(module, "ERROR_CODES", None) or client.ERROR_CODES
    intro = getattr(module, "ERRORS", None) or (
        "Every function raises `pyrunner_integrations.IntegrationError` (a "
        "`pyrunner_connections.ConnectionsError`, so one `except` catches both) with `code`, `status` (the HTTP "
        "status, or None) and `retry_after` (seconds, or None). Its message never holds the connection's "
        "credentials. Before raising, the client retries a 429 (or a 503 with Retry-After) up to "
        f"{client.MAX_RETRIES} times, waiting what the service asks (up to {client.MAX_WAIT:g} s; longer, and "
        f"the error says it in `retry_after`) or else {otherwise}; other 5xx "
        "replies and lost connections only for GET, PUT, DELETE and other calls that are safe to repeat. After "
        "a 401 it asks PyRun once for new credentials (an OAuth token is refreshed then) and tries again."
    )
    lines += ["## Errors", "", intro, "", "| Code | When |", "|---|---|"]
    for code, meaning in codes.items():
        lines.append(f"| `{code}` | {meaning} |")
    lines += [
        "| `CONNECTION_...` | The connection can't be used: `CONNECTION_NOT_FOUND`, `CONNECTION_EXPIRED`... "
        "(see [Connections](../run-context.md#connections)). |",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def write(integrations=None, root=None, check=False) -> list:
    """Write (or with ``check``, only compare) each page; returns the paths that were (or would be) changed."""
    changed = []
    for integration in integrations if integrations is not None else framework.integrations():
        path = path_for(integration, root)
        text = render(integration)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        changed.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return changed
