class DoctorSignatureTests(SimpleTestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="t43-doctor-"))
        self.addCleanup(shutil.rmtree, self.root, True)

    def findings(self, files):
        shutil.rmtree(self.root / SLUG, ignore_errors=True)
        with trusted():
            report = run_doctor(write_folder(self.root, files))
        return [(f.severity, f.message) for f in report.findings if f.rule == "signature"]

    def test_unsigned_folder_adds_no_finding(self):
        self.assertEqual(self.findings(demo_files()), [])

    def test_signed_folder_passes_even_with_pycache(self):
        files = {**signed_files(demo_files()), "__pycache__/apps.cpython-312.pyc": b"\0"}
        [(severity, message)] = self.findings(files)
        self.assertEqual(severity, "pass")
        self.assertIn("Signed by pyrun (key test-1)", message)

    def test_manifest_only_passes(self):
        files = demo_files()
        [(severity, message)] = self.findings({**files, MANIFEST_NAME: manifest_for(files)})
        self.assertEqual(severity, "pass")
        self.assertIn("not signed", message)

    def test_tampered_folder_fails(self):
        [(severity, message)] = self.findings({**signed_files(demo_files()), "apps.py": "# edited\n"})
        self.assertEqual(severity, "fail")
        self.assertIn("apps.py does not match its hash", message)
        self.assertIn("plugin_sign", message)


