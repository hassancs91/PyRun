KEY = Ed25519PrivateKey.generate()
ROTATED = Ed25519PrivateKey.generate()
OTHER = Ed25519PrivateKey.generate()
STRANGER = Ed25519PrivateKey.generate()


def trusted(**extra):
    """TRUSTED_KEYS patched with the test keys (PyRun's two, and acme's)."""
    entries = {
        "test-1": TrustedKey(publisher="pyrun", public_key=public_key_b64(KEY)),
        "test-2": TrustedKey(publisher="pyrun", public_key=public_key_b64(ROTATED)),
        "acme-1": TrustedKey(publisher="acme", public_key=public_key_b64(OTHER)),
        **extra,
    }
    return mock.patch.dict(keys.TRUSTED_KEYS, entries, clear=True)


def manifest_for(files: dict) -> bytes:
    """sha256sum's format, written independently of build_manifest."""
    return "".join(
        f"{hashlib.sha256(content.encode() if isinstance(content, str) else content).hexdigest()}  {rel}\n"
        for rel, content in sorted(files.items())
    ).encode()


def demo_files(version="1.0.0", slug=SLUG, **manifest_extra):
    manifest = {"slug": slug, "name": "Demo", "version": version, **manifest_extra}
    return {
        "plugin.json": json.dumps(manifest),
        "__init__.py": "CALLS = []\n",
        "apps.py": APPS_PY.format(slug=slug),
        "marker.txt": f"version {version}\n",
        "CHANGELOG.md": f"## [{version}]\n",
    }


def signed_files(files, *, key=KEY, key_id="test-1", publisher="pyrun", slug=SLUG, version=None,
                 manifest=None):
    """``files`` plus MANIFEST.sha256 and plugin.sig."""
    manifest = manifest if manifest is not None else manifest_for(files)
    version = version or json.loads(files["plugin.json"])["version"]
    sig = sign_manifest(manifest, key, slug=slug, publisher=publisher, version=version, key_id=key_id)
    return {**files, MANIFEST_NAME: manifest, SIGNATURE_NAME: sig}


def zip_of(files, slug=SLUG) -> io.BytesIO:
    return _zip({f"{slug}/{rel}": content for rel, content in files.items()})


def write_folder(root: Path, files: dict, slug=SLUG) -> Path:
    folder = root / slug
    for rel, content in files.items():
        path = folder / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode() if isinstance(content, str) else content)
    return folder


