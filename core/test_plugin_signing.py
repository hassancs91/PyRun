class PluginSignCommandTests(_Dir):
    def setUp(self):
        super().setUp()
        self.outside = Path(tempfile.mkdtemp(prefix="t43-key-"))
        self.addCleanup(shutil.rmtree, self.outside, True)
        self.key_path = self.outside / "pyrun.pem"
        self.key_path.write_bytes(private_key_pem(KEY))
        self.src = write_folder(self.outside / "src", {
            **demo_files("1.2.0"), "sub/data.json": "{}",
            "__pycache__/apps.cpython-312.pyc": b"\0", ".DS_Store": b"\0", ".git/HEAD": "ref",
        })

    def sign(self, *args, **kw):
        out = io.StringIO()
        call_command("plugin_sign", *args, stdout=out, **kw)
        return out.getvalue()

    def test_signs_a_zip_that_installs_verified(self):
        before = sorted(p.relative_to(self.src).as_posix() for p in self.src.rglob("*"))
        with trusted():
            output = self.sign(str(self.src), key=str(self.key_path), key_id="test-1",
                               out=str(self.outside / "dist"))
            target = self.outside / "dist" / f"{SLUG}-1.2.0.zip"
            self.assertIn("Signed t42demo 1.2.0 as pyrun (key test-1), 6 files", output)
            self.assertNotIn("refuses", output)
            with zipfile.ZipFile(target) as zf:
                names = sorted(zf.namelist())
            self.assertEqual(names, sorted(f"{SLUG}/{rel}" for rel in (
                "plugin.json", "__init__.py", "apps.py", "marker.txt", "CHANGELOG.md", "sub/data.json",
                MANIFEST_NAME, SIGNATURE_NAME,
            )))
            plugin, _, _ = PluginService.upload(io.BytesIO(target.read_bytes()))
        self.assertEqual((plugin.trust, plugin.signed_by, plugin.signing_key_id), ("verified", "pyrun", "test-1"))
        # The source folder is not changed.
        self.assertEqual(sorted(p.relative_to(self.src).as_posix() for p in self.src.rglob("*")), before)

    def test_warns_when_this_pyrun_does_not_trust_the_key(self):
        output = self.sign(str(self.src), key=str(self.key_path), key_id="test-1", out=str(self.outside / "d"))
        self.assertIn("is not in core/plugins/trust/keys.py", output)
        with trusted():
            output = self.sign(str(self.src), key=str(self.key_path), key_id="acme-1", out=str(self.outside / "d"))
        self.assertIn("different key or publisher", output)
        revoked = TrustedKey(publisher="pyrun", public_key=public_key_b64(KEY), revoked=True)
        with trusted(**{"test-1": revoked}):
            output = self.sign(str(self.src), key=str(self.key_path), key_id="test-1", out=str(self.outside / "d"))
        self.assertIn("is revoked", output)

    def test_refuses_a_key_inside_the_project(self):
        with self.assertRaises(CommandError) as caught:
            self.sign(str(self.src), key=str(Path(settings.BASE_DIR) / "keys" / "pyrun.pem"), key_id="test-1")
        self.assertIn("outside this project", str(caught.exception))

    def test_refuses_a_publisher_other_than_the_manifests(self):
        src = write_folder(self.outside / "acme", demo_files("1.0.0", publisher="acme"))
        with self.assertRaises(CommandError) as caught:
            self.sign(str(src), key=str(self.key_path), key_id="test-1", out=str(self.outside / "d"))
        self.assertIn("--publisher acme", str(caught.exception))

    def test_generate_key_writes_a_new_key_and_prints_the_entry(self):
        path = self.outside / "new" / "key.pem"
        output = self.sign(generate_key=str(path), key_id="pyrun-2027")
        private = load_private_key(path.read_bytes())
        self.assertIn(f'"pyrun-2027": TrustedKey(publisher="pyrun", public_key="{public_key_b64(private)}")', output)
        with self.assertRaises(CommandError):
            self.sign(generate_key=str(path), key_id="pyrun-2027")  # never overwrites
        with self.assertRaises(CommandError):
            self.sign(generate_key=str(Path(settings.BASE_DIR) / "k.pem"), key_id="x")
        self.assertFalse((Path(settings.BASE_DIR) / "k.pem").exists())


