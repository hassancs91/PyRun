    def test_backup_round_trips_the_policy(self):
        settings_obj = GlobalSettings.get_settings()
        settings_obj.plugin_trust_policy = "signed_only"
        settings_obj.save()
        data = BackupService.create_backup(include_runs=False)
        self.assertEqual(data["global_settings"]["plugin_trust_policy"], "signed_only")
        settings_obj.plugin_trust_policy = "allow_unsigned"
        settings_obj.save()
        BackupService.restore_backup(data, restore_runs=False, current_user=self.admin)
        self.assertEqual(GlobalSettings.get_settings().plugin_trust_policy, "signed_only")
        # An older backup (no key) or an unknown value: the default.
        for value in (None, "everything", 1):
            with self.subTest(value=value):
                copy = json.loads(json.dumps(data))
                if value is None:
                    del copy["global_settings"]["plugin_trust_policy"]
                else:
                    copy["global_settings"]["plugin_trust_policy"] = value
                BackupService.restore_backup(copy, restore_runs=False, current_user=self.admin)
                self.assertEqual(GlobalSettings.get_settings().plugin_trust_policy, "allow_unsigned")
