class InstallTrustTests(_Dir):
    def setUp(self):
        super().setUp()
        patcher = trusted()
        patcher.start()
        self.addCleanup(patcher.stop)

    def set_policy(self, policy):
        settings_obj = GlobalSettings.get_settings()
        settings_obj.plugin_trust_policy = policy
        settings_obj.save()

    def install_files(self, files):
        plugin, update, _ = PluginService.upload(zip_of(files))
        self.assertIsNone(update)
        return plugin

    def test_signed_install_is_verified_and_pinned(self):
        plugin = self.install_files(signed_files(demo_files()))
        self.assertEqual(
            (plugin.trust, plugin.signed_by, plugin.signing_key_id, plugin.pinned_publisher),
            ("verified", "pyrun", "test-1", "pyrun"),
        )
        self.assertTrue(plugin.verified_by_pyrun)
        self.assertTrue((self.root / SLUG / SIGNATURE_NAME).is_file())

    def test_another_publishers_signature_is_verified_without_the_pyrun_badge(self):
        plugin = self.install_files(signed_files(demo_files(), key=OTHER, key_id="acme-1", publisher="acme"))
        self.assertEqual((plugin.trust, plugin.signed_by), ("verified", "acme"))
        self.assertFalse(plugin.verified_by_pyrun)

    def test_unsigned_install_is_allowed_by_default(self):
        plugin = self.install_files(demo_files())
        self.assertEqual((plugin.trust, plugin.signed_by, plugin.pinned_publisher), ("unsigned", "", ""))
        self.assertFalse(plugin.verified_by_pyrun)

    def test_tampered_install_is_refused_and_leaves_nothing(self):
        files = {**signed_files(demo_files()), "marker.txt": "tampered"}
        with self.assertRaises(PluginInstallError) as caught:
            PluginService.upload(zip_of(files))
        self.assertIn("failed its signature check", str(caught.exception))
        self.assertIn("marker.txt does not match its hash", str(caught.exception))
        self.assertIn("Get an untouched copy", str(caught.exception))
        self.assertFalse(Plugin.objects.filter(slug=SLUG).exists())
        self.assertFalse((self.root / SLUG).exists())

    def test_signed_only_refuses_unsigned_installs(self):
        self.set_policy("signed_only")
        with self.assertRaises(PluginInstallError) as caught:
            PluginService.upload(zip_of(demo_files()))
        self.assertIn("only accepts signed plugins", str(caught.exception))
        self.assertFalse((self.root / SLUG).exists())
        self.assertEqual(self.install_files(signed_files(demo_files())).trust, "verified")

    def update(self, files):
        return PluginService.upload(zip_of(files), user=self.admin)

    def refused_update(self, files, fragment):
        before = self.live()
        with self.assertRaises(PluginInstallError) as caught:
            self.update(files)
        self.assertIn(fragment, str(caught.exception))
        self.assertEqual(self.live(), before)
        row = PluginUpdate.objects.filter(plugin__slug=SLUG).latest("created_at")
        self.assertEqual(row.outcome, PluginUpdate.Outcome.REFUSED)
        self.assertIn(fragment, row.error)

    def test_pinned_slug_refuses_unsigned_and_other_publishers(self):
        self.install_files(signed_files(demo_files("1.0.0")))
        self.refused_update(demo_files("1.1.0"), "was installed signed by 'pyrun'")
        self.refused_update(
            signed_files(demo_files("1.1.0"), key=OTHER, key_id="acme-1", publisher="acme"),
            "A plugin can't change publisher",
        )
        plugin = Plugin.objects.get(slug=SLUG)
        self.assertEqual((plugin.version, plugin.signing_key_id), ("1.0.0", "test-1"))

    def test_a_new_key_id_of_the_same_publisher_updates(self):
        self.install_files(signed_files(demo_files("1.0.0")))
        plugin, row, _ = self.update(signed_files(demo_files("1.1.0"), key=ROTATED, key_id="test-2"))
        self.assertEqual(row.outcome, PluginUpdate.Outcome.PENDING)
        self.assertEqual((plugin.version, plugin.trust, plugin.signing_key_id, plugin.pinned_publisher),
                         ("1.1.0", "verified", "test-2", "pyrun"))

    def test_an_unsigned_plugin_updated_signed_gets_pinned(self):
        self.install_files(demo_files("1.0.0"))
        plugin, _, _ = self.update(signed_files(demo_files("1.1.0")))
        self.assertEqual((plugin.trust, plugin.pinned_publisher), ("verified", "pyrun"))
        self.refused_update(demo_files("1.2.0"), "This zip is not signed")

    def test_tampered_update_is_refused(self):
        self.install_files(demo_files("1.0.0"))
        self.refused_update({**signed_files(demo_files("1.1.0")), "marker.txt": "x"}, "does not match its hash")
        self.assertEqual(Plugin.objects.get(slug=SLUG).version, "1.0.0")

    def test_signed_only_refuses_unsigned_updates(self):
        self.install_files(demo_files("1.0.0"))
        self.set_policy("signed_only")
        self.refused_update(demo_files("1.1.0"), "only accepts signed plugins")

    def test_rollback_restores_the_kept_folders_trust_but_keeps_the_pin(self):
        self.install_files(demo_files("1.0.0"))
        self.update(signed_files(demo_files("1.1.0")))
        # The live folder of 1.0.0 was loaded here once: its __pycache__ is not a tamper.
        cache = self.root / ".previous" / f"{SLUG}-1.0.0" / "__pycache__"
        cache.mkdir()
        (cache / "apps.cpython-312.pyc").write_bytes(b"\0")
        plugin = Plugin.objects.get(slug=SLUG)
        plugin.previous_checksum = PluginService._checksum_dir(cache.parent)
        plugin.save(update_fields=["previous_checksum"])

        PluginService.rollback(plugin, user=self.admin)
        plugin.refresh_from_db()
        self.assertEqual((plugin.version, plugin.trust, plugin.signed_by, plugin.signing_key_id),
                         ("1.0.0", "unsigned", "", ""))
        self.assertEqual(plugin.pinned_publisher, "pyrun")

    def test_rollback_to_a_signed_version_is_verified(self):
        self.install_files(signed_files(demo_files("1.0.0")))
        plugin, _, _ = self.update(signed_files(demo_files("1.1.0"), key=ROTATED, key_id="test-2"))
        PluginService.rollback(plugin, user=self.admin)
        plugin.refresh_from_db()
        self.assertEqual((plugin.version, plugin.trust, plugin.signing_key_id), ("1.0.0", "verified", "test-1"))

    def test_signed_only_refuses_rolling_back_to_unsigned(self):
        self.install_files(demo_files("1.0.0"))
        plugin, _, _ = self.update(signed_files(demo_files("1.1.0")))
        self.set_policy("signed_only")
        with self.assertRaises(PluginInstallError) as caught:
            PluginService.rollback(plugin, user=self.admin)
        self.assertIn("only accepts signed plugins", str(caught.exception))
        self.assertEqual(Plugin.objects.get(slug=SLUG).version, "1.1.0")
        self.assertIn("version 1.1.0", self.live())

    def test_signed_only_refuses_activating_unsigned(self):
        unsigned = self.install_files(demo_files())
        self.set_policy("signed_only")
        with _no_preflight():
            ok, output = PluginService.activate(unsigned)
        self.assertFalse(ok)
        self.assertIn("only accepts signed plugins", output)
        unsigned.refresh_from_db()
        self.assertEqual(unsigned.status, Plugin.Status.INSTALLED)
        self.assertIn("only accepts signed plugins", unsigned.error_message)

    def test_signed_only_activates_a_verified_plugin(self):
        plugin = self.install_files(signed_files(demo_files()))
        self.set_policy("signed_only")
        with _no_preflight():
            ok, output = PluginService.activate(plugin)
        self.assertTrue(ok, output)

    def test_a_signed_folder_edited_on_disk_cannot_be_activated(self):
        plugin = self.install_files(signed_files(demo_files()))
        (self.root / SLUG / "marker.txt").write_text("edited on the server", encoding="utf-8")
        with _no_preflight():
            ok, output = PluginService.activate(plugin)
        self.assertFalse(ok)
        self.assertIn("signature", output)
        self.assertIn("marker.txt does not match its hash", output)


