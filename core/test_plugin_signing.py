"""
Plugin signing and the Verified badge (2.5 T43).

What this pins, roughly in order of how much it would hurt to get wrong:

- A zip whose MANIFEST.sha256 or plugin.sig doesn't check out is refused, on
  install and on update, and leaves nothing behind: a changed, missing or
  unlisted file, a bad signature, an unknown or revoked key id, a signature
  for another slug, version or publisher.
- A valid signature installs as trust=verified (the "Verified · PyRun" badge),
  none as unsigned (allowed by default).
- Key pinning: a slug installed signed only updates with a zip signed by the
  same publisher (a new key id of that publisher is a rotation).
- plugin_trust_policy signed_only refuses unsigned installs, updates,
  rollbacks and activations; it round-trips through a backup.
- The doctor checks a signed folder; plugin_sign builds a zip that installs as
  verified and never takes a key from inside the project.
- The console shows the badge and saves the policy; plugins.list reports trust.

Every key here is generated by the test. No real key exists in the repo.
"""

