class SigningTests(SimpleTestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="t43-sign-"))
        self.addCleanup(shutil.rmtree, self.root, True)

    def verify(self, files, **kw):
        folder = write_folder(self.root, files)
        manifest = json.loads(files["plugin.json"])
        with trusted():
            return verify_folder(folder, slug=SLUG, manifest=manifest, **kw)

    def refused(self, files, fragment, **kw):
        with self.assertRaises(TrustError) as caught:
            self.verify(files, **kw)
        self.assertIn(fragment, str(caught.exception))

    def test_manifest_is_sha256sum_format_without_trust_or_generated_files(self):
        files = demo_files()
        folder = write_folder(self.root, {
            **files, "sub/data.json": "{}", "__pycache__/apps.cpython-312.pyc": b"\0",
            "stray.pyc": b"\0", MANIFEST_NAME: "old", SIGNATURE_NAME: "old",
        })
        self.assertEqual(build_manifest(folder), manifest_for({**files, "sub/data.json": "{}"}))

    def test_parse_manifest_refuses_malformed_input(self):
        good = "a" * 64
        for data, fragment in (
            (b"not a line\n", "is not '<sha256>  <path>'"),
            (f"{good}  ../escape.py\n".encode(), "unsafe path"),
            (f"{good}  /abs.py\n".encode(), "unsafe path"),
            (f"{good}  a\\b.py\n".encode(), "unsafe path"),
            (f"{good}  a.py\n{good}  a.py\n".encode(), "twice"),
            (f"{good}  {SIGNATURE_NAME}\n".encode(), "must not list"),
            (b"", "lists no files"),
            (b"\xff\xfe", "not UTF-8"),
        ):
            with self.subTest(data=data), self.assertRaises(TrustError) as caught:
                parse_manifest(data)
            self.assertIn(fragment, str(caught.exception))

    def test_no_trust_files_is_unsigned(self):
        result = self.verify(demo_files())
        self.assertEqual((result.trust, result.publisher, result.key_id), ("unsigned", "", ""))

    def test_a_manifest_alone_is_checked_and_unsigned(self):
        files = demo_files()
        self.assertFalse(self.verify({**files, MANIFEST_NAME: manifest_for(files)}).verified)
        shutil.rmtree(self.root / SLUG)
        changed = {**files, MANIFEST_NAME: manifest_for(files), "marker.txt": "edited"}
        self.refused(changed, "marker.txt does not match its hash")

    def test_valid_signature_is_verified(self):
        result = self.verify(signed_files(demo_files()))
        self.assertTrue(result.verified)
        self.assertEqual((result.publisher, result.key_id), ("pyrun", "test-1"))

    def test_signature_problems_are_refused(self):
        files = demo_files()
        good = signed_files(files)
        sig = json.loads(good[SIGNATURE_NAME])
        cases = [
            ({**good, "marker.txt": "tampered"}, "marker.txt does not match its hash"),
            ({**good, "extra.py": "x = 1"}, "extra.py is not listed"),
            ({k: v for k, v in good.items() if k != "marker.txt"}, "marker.txt is listed but missing"),
            ({**good, "__pycache__/x.cpython-312.pyc": b"\0"}, "__pycache__/x.cpython-312.pyc is not listed"),
            ({**files, SIGNATURE_NAME: good[SIGNATURE_NAME]}, f"no {MANIFEST_NAME}"),
            (signed_files(files, key_id="nobody"), "key id 'nobody', which this PyRun does not trust"),
            (signed_files(files, key=STRANGER), "does not match its contents"),
            (signed_files(files, publisher="acme"), "belongs to the publisher 'pyrun', not 'acme'"),
            (signed_files(files, slug="other"), "for the plugin 'other'"),
            (signed_files(files, version="9.9.9"), "for version '9.9.9'"),
            (signed_files(demo_files(publisher="acme")), "plugin.json names the publisher 'acme'"),
            ({**good, SIGNATURE_NAME: "{"}, "not valid JSON"),
            ({**good, SIGNATURE_NAME: json.dumps({**sig, "format": 2})}, "format 2"),
            ({**good, SIGNATURE_NAME: json.dumps({**sig, "key_id": ""})}, "missing 'key_id'"),
            ({**good, SIGNATURE_NAME: json.dumps({**sig, "signature": "%%%"})}, "not valid base64"),
            # The manifest itself edited after signing (a hash swapped for the tampered file's).
            ({**good, "marker.txt": "tampered", MANIFEST_NAME: manifest_for({**files, "marker.txt": "tampered"})},
             "does not match its contents"),
        ]
        for case, fragment in cases:
            with self.subTest(fragment=fragment):
                shutil.rmtree(self.root / SLUG, ignore_errors=True)
                self.refused(case, fragment)

    def test_revoked_key_is_refused(self):
        folder = write_folder(self.root, signed_files(demo_files()))
        revoked = TrustedKey(publisher="pyrun", public_key=public_key_b64(KEY), revoked=True)
        with trusted(**{"test-1": revoked}), self.assertRaises(TrustError) as caught:
            verify_folder(folder, slug=SLUG, manifest=json.loads(demo_files()["plugin.json"]))
        self.assertIn("has been revoked", str(caught.exception))

    def test_generated_files_can_be_skipped_for_a_loaded_folder(self):
        files = {**signed_files(demo_files()), "__pycache__/apps.cpython-312.pyc": b"\0"}
        self.assertTrue(self.verify(files, include_generated=False).verified)

    def test_signed_message_binds_every_field(self):
        base = dict(slug="a", publisher="pyrun", version="1.0.0", key_id="k")
        message = signed_message(b"m", **base)
        for field, value in (("slug", "b"), ("publisher", "acme"), ("version", "1.0.1"), ("key_id", "j")):
            self.assertNotEqual(signed_message(b"m", **{**base, field: value}), message)
        self.assertNotEqual(signed_message(b"n", **base), message)

    def test_verify_signature_for_other_documents(self):
        message = b"an index"
        signature = base64.b64encode(KEY.sign(message)).decode()
        with trusted():
            self.assertEqual(verify_signature(message, signature, "test-1", "pyrun").publisher, "pyrun")
            with self.assertRaises(TrustError):
                verify_signature(b"another index", signature, "test-1", "pyrun")

    def test_sign_refuses_bad_fields(self):
        for kw in ({"publisher": "Bad Name"}, {"key_id": "has space"}, {"key_id": ""}):
            args = {"slug": SLUG, "publisher": "pyrun", "version": "1.0.0", "key_id": "k", **kw}
            with self.subTest(kw=kw), self.assertRaises(TrustError):
                sign_manifest(b"m", KEY, **args)

    def test_shipped_keys_are_public_keys_only(self):
        # Holds whether TRUSTED_KEYS is empty or carries PyRun's real key: every
        # entry is a well-formed Ed25519 PUBLIC key, and the module holds no
        # private key material (PEM, or a 64-byte seed + public key pair).
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

        self.assertEqual(keys.PYRUN_PUBLISHER, "pyrun")
        self.assertIsInstance(keys.TRUSTED_KEYS, dict)
        for key_id, entry in keys.TRUSTED_KEYS.items():
            with self.subTest(key_id=key_id):
                self.assertIsInstance(key_id, str)
                self.assertTrue(key_id.strip())
                self.assertIsInstance(entry, keys.TrustedKey)
                self.assertTrue(entry.publisher)
                self.assertIsInstance(entry.revoked, bool)
                raw = base64.b64decode(entry.public_key, validate=True)
                self.assertEqual(len(raw), 32)
                Ed25519PublicKey.from_public_bytes(raw)  # raises if it isn't one
        source = Path(keys.__file__).read_text(encoding="utf-8")
        self.assertNotIn("PRIVATE KEY", source)
        for literal in re.findall(r"[A-Za-z0-9+/]{40,}={0,2}", source):
            try:
                decoded = base64.b64decode(literal, validate=True)
            except ValueError:
                continue
            self.assertNotEqual(len(decoded), 64, "a 64-byte key pair in keys.py")


